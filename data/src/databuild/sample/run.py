"""Builds the open sample from Wikidata and TVmaze.

It writes the same pull file the TMDB pull writes, so every later stage runs unchanged. It reads no
key and needs no private input. Three settings turn it on: `open.wikidata_endpoint`,
`open.tvmaze_api_base` and `open.user_agent`.

Open sources hold no rating and no vote count. A title takes the neutral rating below, the same
value the server's rating rule uses as its prior, so the rating adds nothing to a title's rank and
page gates still pass. Popularity is the number of Wikipedia languages covering a title. No title
holds a certificate, so age rules refuse every title below 18 on this data.
"""

from __future__ import annotations

import json
import os
import re
import sqlite3
import time
from collections.abc import Callable
from typing import Any

from ..context import Context
from ..embed.text import full_text
from ..errors import StageFailed
from ..export.files import BY_ROLE
from ..keys import title_key
from ..pull.tmdb import COLUMNS, open_pull, pull_db
from ..settings import need
from ..vocab import load
from .cards import Card, backdrop_path, poster_path, write_cards
from .tvmaze import Show, TvMaze, parse_show
from .wikidata import Facts, Listed, Wikidata, describe_film, list_films, list_series, read_facts

OPEN_TEXT_FILE = "open_text.jsonl"
FILM_SHARE = 0.6
LIST_MARGIN = 1.5
NEUTRAL_RATING = 6.0
MIN_TEXT = 60
GENRE_WORDS = (
    ("science.fiction", "Science Fiction"),
    ("sci.fi", "Science Fiction"),
    ("cyberpunk", "Science Fiction"),
    ("anim(e|ated|ation)", "Animation"),
    ("documentary", "Documentary"),
    ("comedy", "Comedy"),
    ("romantic", "Romance"),
    ("romance", "Romance"),
    ("horror", "Horror"),
    ("thriller", "Thriller"),
    ("espionage", "Thriller"),
    ("action", "Action"),
    ("adventure", "Adventure"),
    ("crime", "Crime"),
    ("gangster", "Crime"),
    ("heist", "Crime"),
    ("legal", "Crime"),
    ("drama", "Drama"),
    ("medical", "Drama"),
    ("fantasy", "Fantasy"),
    ("supernatural", "Fantasy"),
    ("war", "War"),
    ("western", "Western"),
    ("music(al)?", "Music"),
    ("mystery", "Mystery"),
    ("histor(y|ical)", "History"),
    ("biographical", "History"),
    ("family", "Family"),
    ("children", "Family"),
)
_GENRES = tuple((re.compile(rf"\b{w}\b", re.IGNORECASE), name) for w, name in GENRE_WORDS)
_ADULT = re.compile("pornograph", re.IGNORECASE)
SOURCES_TEXT = """# Sources of this set

Film facts come from Wikidata, under CC0. Each film's text is a sentence made from those facts.
Series text comes from TVmaze, under CC BY-SA 4.0. See tvmaze/CREDIT.md.
Title ids are TMDB ids as Wikidata records them. No text, image or number comes from TMDB.
Cards are generated by this builder and are free of any claim.
Ratings are one neutral value and popularity is a count of Wikipedia languages.
"""
CREDIT_TEXT = """# Credit

Series names, summaries and episode text in this folder come from TVmaze, under CC BY-SA 4.0.
The series rows of catalog.db hold the same text, marked with the source tvmaze.
Each line of series.jsonl gives the page of its show in the field url.
This text is shared under the same licence.
"""


def plain_genres(words: list[str]) -> list[str]:
    """Plain genre names, in a fixed order, from Wikidata labels or TVmaze genres."""
    return sorted({name for word in words for rule, name in _GENRES if rule.search(word)})


def series_genres(words: list[str], tv_names: dict[str, str]) -> list[str]:
    return sorted({tv_names.get(g, g) for g in plain_genres(words)})


def pull_row(kind: str, title_id: int, title: str, source: str, at: int) -> dict[str, Any]:
    """A pull row with every list empty. What a source does not hold stays empty."""
    row: dict[str, Any] = dict.fromkeys(COLUMNS)
    row.update(
        media_type=kind,
        id=title_id,
        title=title,
        source=source,
        fetched_at=at,
        adult=0,
        status=None,
        vote_average=NEUTRAL_RATING,
        vote_count=0,
        poster_path=poster_path(kind, title_id),
        backdrop_path=backdrop_path(kind, title_id),
        certs="{}",
        translations="{}",
    )
    for name in (
        "directors",
        "creators",
        "cast_members",
        "crew",
        "keywords",
        "origin_country",
        "production_companies",
        "company_logos",
        "networks",
        "network_logos",
        "spoken_languages",
        "videos",
    ):
        row[name] = "[]"
    return row


def film_row(listed: Listed, facts: Facts, at: int) -> dict[str, Any] | None:
    """A film, or None when its facts make too little text."""
    labels = facts.all("genres")
    if not facts.label or any(_ADULT.search(word) for word in labels):
        return None
    genres = plain_genres(labels)
    text = describe_film(facts, genres)
    if len(text) < MIN_TEXT:
        return None
    row = pull_row("movie", listed.title_id, facts.label, "wikidata", at)
    languages = facts.all("languages")
    row.update(
        overview=text,
        genres=", ".join(genres),
        popularity=float(listed.links),
        release_date=facts.date,
        runtime=facts.runtime,
        directors=json.dumps(facts.all("directors")[:3], ensure_ascii=False),
        cast_members=json.dumps(facts.all("cast")[:10], ensure_ascii=False),
        keywords=json.dumps([s.lower() for s in facts.all("subjects")], ensure_ascii=False),
        origin_country=json.dumps(facts.all("countries")),
        original_language=languages[0] if languages else "",
    )
    return row


def series_row(
    listed: Listed, facts: Facts, show: Show, tv_names: dict[str, str], at: int
) -> dict[str, Any] | None:
    """A series, or None when TVmaze holds too little text for it."""
    if len(show.text) < MIN_TEXT or any(_ADULT.search(word) for word in facts.all("genres")):
        return None
    row = pull_row("tv", listed.title_id, facts.label or show.name, "tvmaze", at)
    row.update(
        overview=show.text,
        genres=", ".join(series_genres(show.genres + facts.all("genres"), tv_names)),
        popularity=float(listed.links),
        release_date=show.premiered or facts.date,
        runtime=show.runtime,
        creators=json.dumps(facts.all("creators")[:3], ensure_ascii=False),
        cast_members=json.dumps(facts.all("cast")[:10], ensure_ascii=False),
        keywords=json.dumps([s.lower() for s in facts.all("subjects")], ensure_ascii=False),
        origin_country=json.dumps(show.countries or facts.all("countries")),
        original_language=show.language,
        networks=json.dumps(show.networks, ensure_ascii=False),
        tv_type=show.tv_type,
        status=show.status,
        seasons=len(show.seasons),
        episodes=len(show.episodes),
    )
    return row


def find_show(maze: TvMaze, listed: Listed) -> dict[str, Any] | None:
    """The show by its own id, else through its IMDb id."""
    maze_id = listed.maze
    if maze_id is None and listed.imdb:
        maze_id = maze.lookup(listed.imdb)
    return maze.show(maze_id) if maze_id is not None else None


def insert_rows(db: sqlite3.Connection, rows: list[dict[str, Any]]) -> None:
    names = ",".join(COLUMNS)
    marks = ",".join("?" * len(COLUMNS))
    db.executemany(
        f"INSERT INTO titles ({names}) VALUES ({marks})",
        [[row[c] for c in COLUMNS] for row in rows],
    )
    db.executemany(
        "INSERT INTO fetch_log VALUES (?,?,200)", [(r["media_type"], r["id"]) for r in rows]
    )


def open_line(row: dict[str, Any]) -> str:
    """One line of open text. The title stays out, as in the full recipe."""
    kind = row["media_type"]
    people = row["directors"] if kind == "movie" else row["creators"]
    text = full_text(
        kind,
        row["genres"],
        "",
        row["overview"],
        ", ".join(json.loads(people)),
        row["cast_members"],
    )
    return json.dumps({"key": title_key(kind, row["id"]), "text": text}, ensure_ascii=False)


def _write(path: Any, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def series_lines(shows: list[tuple[dict[str, Any], Show]]) -> str:
    lines = []
    for row, show in shows:
        line = {
            "key": title_key("tv", row["id"]),
            "tvmaze_id": show.maze_id,
            "url": show.url,
            "name": show.name,
            "summary": show.text,
            "episodes": [
                {"s": e[1], "e": e[2], "name": e[3], "summary": e[4]} for e in show.episodes
            ],
        }
        lines.append(json.dumps(line, ensure_ascii=False))
    return "\n".join(lines) + ("\n" if lines else "")


def pull_open(ctx: Context, sleep: Callable[[float], None] = time.sleep) -> None:
    """Pulls the sample and writes the pull file, open text, series folder, cards and sources."""
    settings = ctx.settings.open
    endpoint = need(settings.wikidata_endpoint, "open.wikidata_endpoint")
    base = need(settings.tvmaze_api_base, "open.tvmaze_api_base")
    agent = need(settings.user_agent, "open.user_agent")
    client = Wikidata(endpoint, agent, ctx.transport, sleep)
    maze = TvMaze(base, agent, ctx.transport, settings.tvmaze_rps, sleep)
    at = int(ctx.now().timestamp())
    tv_names = load("rows")["tv_genre_names"]
    want_films = round(settings.titles * FILM_SHARE)
    want_series = settings.titles - want_films

    films = list_films(client, round(want_films * LIST_MARGIN), settings.min_links)
    series = list_series(client, round(want_series * LIST_MARGIN), settings.min_links)
    facts = read_facts(client, [x.item for x in films + series])

    rows: list[dict[str, Any]] = []
    for listed in films:
        if len(rows) >= want_films:
            break
        row = film_row(listed, facts[listed.item], at)
        if row:
            rows.append(row)
    made_films = len(rows)
    shows: list[tuple[dict[str, Any], Show]] = []
    for listed in series:
        if len(shows) >= want_series:
            break
        document = find_show(maze, listed)
        if document is None:
            continue
        show = parse_show(document, listed.title_id)
        row = series_row(listed, facts[listed.item], show, tv_names, at)
        if row:
            rows.append(row)
            shows.append((row, show))
    if not rows:
        raise StageFailed("sample: no title has enough text")

    path = pull_db(ctx)
    for name in (path, path.with_name(path.name + "-wal"), path.with_name(path.name + "-shm")):
        name.unlink(missing_ok=True)
    db = open_pull(path)
    insert_rows(db, rows)
    for _, show in shows:
        db.executemany("INSERT INTO seasons VALUES (?,?,?,?,?,?,?)", show.seasons)
        db.executemany("INSERT INTO episodes VALUES (?,?,?,?,?,?,?,?,?)", show.episodes)
    db.commit()
    db.close()

    _write(ctx.work / OPEN_TEXT_FILE, "\n".join(open_line(r) for r in rows) + "\n")
    _write(ctx.out / BY_ROLE["series_text"].path, series_lines(shows))
    _write(ctx.out / BY_ROLE["series_credit"].path, CREDIT_TEXT)
    _write(ctx.out / BY_ROLE["sources"].path, SOURCES_TEXT)
    cards = [
        Card(
            r["media_type"],
            r["id"],
            r["title"],
            (r["release_date"] or "")[:4],
        )
        for r in rows
    ]
    made = write_cards(ctx.out / BY_ROLE["cards"].path, cards)
    ctx.say(
        f"sample: {made_films} films from Wikidata, {len(shows)} series from TVmaze, "
        f"{len(rows)} titles, {made} cards"
    )
