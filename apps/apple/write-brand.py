#!/usr/bin/env python3
"""Writes what the Apple apps take from brand.json and deployment config: Brand.xcconfig and
Deployment.xcconfig, Info.plist copies bound to the server under target/, the brand's mark as a
vector image the screens draw by the name `mark`, and the brand's corners as Swift constants. All
are generated and ignored by git."""
import ipaddress
import json
import os
import plistlib
from pathlib import Path
from urllib.parse import urlsplit

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
brand = json.loads((ROOT / "brand.json").read_text("utf-8"))

OWN_V4 = (
    ipaddress.IPv4Network("127.0.0.0/8"),
    ipaddress.IPv4Network("10.0.0.0/8"),
    ipaddress.IPv4Network("172.16.0.0/12"),
    ipaddress.IPv4Network("192.168.0.0/16"),
    ipaddress.IPv4Network("169.254.0.0/16"),
)


def is_own_network(host: str) -> bool:
    if host == "localhost" or host.endswith(".local") or host == "::1":
        return True
    try:
        addr = ipaddress.ip_address(host)
    except ValueError:
        return False
    if isinstance(addr, ipaddress.IPv4Address):
        return any(addr in net for net in OWN_V4)
    return addr == ipaddress.IPv6Address("::1")


def resolve_server() -> tuple[str, bool]:
    raw = os.environ.get("STREAMS_SERVER", "").strip()
    if not raw:
        dep_path = ROOT / "deployment.json"
        if dep_path.is_file():
            dep = json.loads(dep_path.read_text("utf-8"))
            raw = str(dep.get("server", "")).strip()
    if not raw:
        return "", False
    lower = raw.lower()
    if not (lower.startswith("https://") or lower.startswith("http://")):
        raise SystemExit(f"refusing server address {raw!r}: must start with https:// or http://")
    server = raw.rstrip("/")
    parsed = urlsplit(server)
    host = (parsed.hostname or "").lower()
    if not host:
        raise SystemExit(f"refusing server address {raw!r}: missing host")
    plain_http = server.lower().startswith("http://")
    if plain_http and not is_own_network(host):
        raise SystemExit(
            f"refusing plain http server address {server!r}: only own-network hosts are allowed without https://"
        )
    return server, plain_http


def write(path: Path, text: str) -> None:
    """Writes only on a change, so Xcode does not rebuild what did not move."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text("utf-8") != text:
        path.write_text(text, "utf-8")


def write_bytes(path: Path, data: bytes) -> None:
    """Writes binary content only on a change."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


server, plain_http = resolve_server()
escaped_server = server.replace("//", "/$()/")

write(
    HERE / "Deployment.xcconfig",
    "// Generated by write-brand.py. Do not commit.\n"
    f"SERVER = {escaped_server}\n"
    "DEPLOYMENT_INFOPLIST_APP = ../target/App-Info.plist\n"
    "DEPLOYMENT_INFOPLIST_PHONE = ../target/Phone-Info.plist\n",
)

write(
    HERE / "Brand.xcconfig",
    "// Generated from brand.json by write-brand.py. Do not commit.\n"
    f"PRODUCT_NAME = {brand['name']}\n"
    f"PRODUCT_BUNDLE_IDENTIFIER = {brand['command']}.app\n"
    '#include? "Deployment.xcconfig"\n',
)

for src_rel, dst_rel in (
    ("App/Info.plist", "target/App-Info.plist"),
    ("PhoneApp/Info.plist", "target/Phone-Info.plist"),
):
    plist = plistlib.loads((HERE / src_rel).read_bytes())
    plist["SERVER"] = server
    if plain_http:
        plist["NSAppTransportSecurity"] = {"NSAllowsLocalNetworking": True}
    else:
        plist.pop("NSAppTransportSecurity", None)
    write_bytes(HERE / dst_rel, plistlib.dumps(plist, fmt=plistlib.FMT_XML, sort_keys=False))

catalog = HERE / "Sources/SurfacesShared/Resources/Brand.xcassets"
write(catalog / "Contents.json", json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
mark = catalog / "mark.imageset"
mark_svg = (ROOT / brand["assets"] / "mark.svg").read_text("utf-8")
write(mark / "mark.svg", mark_svg)
write(
    mark / "Contents.json",
    json.dumps(
        {
            "images": [{"filename": "mark.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True},
        },
        indent=2,
    )
    + "\n",
)

# Layered tvOS icon: Back, Middle, Front
bg_color = brand["colors"].get("background", "#0b0b10")
surface_color = brand["colors"].get("surface", "#16161d")
accent_color = brand["colors"].get("accent", "#2f6bff")

back_svg = f"""<svg width="400" height="240" viewBox="0 0 400 240" xmlns="http://www.w3.org/2000/svg">
<defs>
  <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
    <stop offset="0%" stop-color="{surface_color}"/>
    <stop offset="100%" stop-color="{bg_color}"/>
  </linearGradient>
</defs>
<rect width="400" height="240" fill="url(#bg)"/>
</svg>"""

middle_svg = f"""<svg width="400" height="240" viewBox="0 0 400 240" xmlns="http://www.w3.org/2000/svg">
<circle cx="200" cy="120" r="80" fill="{accent_color}" opacity="0.15" filter="blur(20px)"/>
</svg>"""

front_svg = mark_svg

icon_stack = catalog / "App Icon.imagestack"
write(
    icon_stack / "Contents.json",
    json.dumps(
        {
            "info": {"author": "xcode", "version": 1},
            "layers": [
                {"filename": "Front.imagestacklayer"},
                {"filename": "Middle.imagestacklayer"},
                {"filename": "Back.imagestacklayer"},
            ],
        },
        indent=2,
    )
    + "\n",
)

for layer_name, svg_content in [
    ("Back", back_svg),
    ("Middle", middle_svg),
    ("Front", front_svg),
]:
    layer_dir = icon_stack / f"{layer_name}.imagestacklayer" / "Content.imageset"
    write(layer_dir / "content.svg", svg_content)
    write(
        layer_dir / "Contents.json",
        json.dumps(
            {
                "images": [
                    {"filename": "content.svg", "idiom": "tv", "scale": "1x"},
                    {"filename": "content.svg", "idiom": "tv", "scale": "2x"},
                ],
                "info": {"author": "xcode", "version": 1},
                "properties": {"preserves-vector-representation": True},
            },
            indent=2,
        )
        + "\n",
    )
    write(
        icon_stack / f"{layer_name}.imagestacklayer" / "Contents.json",
        json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n",
    )

# Top Shelf wide banner
top_shelf = catalog / "Top Shelf Image.imageset"
top_shelf_svg = f"""<svg width="1920" height="720" viewBox="0 0 1920 720" xmlns="http://www.w3.org/2000/svg">
<defs>
  <linearGradient id="tsbg" x1="0%" y1="0%" x2="100%" y2="100%">
    <stop offset="0%" stop-color="{surface_color}"/>
    <stop offset="100%" stop-color="{bg_color}"/>
  </linearGradient>
</defs>
<rect width="1920" height="720" fill="url(#tsbg)"/>
<g transform="translate(860, 260) scale(2)">
{mark_svg.split("<svg", 1)[-1].split(">", 1)[-1].rsplit("</svg>", 1)[0] if "<svg" in mark_svg else mark_svg}
</g>
</svg>"""

write(top_shelf / "topshelf.svg", top_shelf_svg)
write(
    top_shelf / "Contents.json",
    json.dumps(
        {
            "images": [
                {"filename": "topshelf.svg", "idiom": "tv", "scale": "1x"},
                {"filename": "topshelf.svg", "idiom": "tv", "scale": "2x"},
            ],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True},
        },
        indent=2,
    )
    + "\n",
)

shape = brand["shape"]
write(
    HERE / "Sources/SurfacesShared/BrandShape.swift",
    "// Generated from brand.json by write-brand.py. Do not commit.\n"
    "import CoreGraphics\n\n"
    "/// The brand's corners from brand.json `shape`, in points on a phone. Each family scales them.\n"
    "public enum Corner {\n"
    f"    public static let card: CGFloat = {shape['card_radius']}\n"
    f"    public static let panel: CGFloat = {shape['panel_radius']}\n"
    f"    public static let field: CGFloat = {shape['field_radius']}\n"
    f"    public static let button: CGFloat = {shape['button_radius']}\n"
    f"    public static let chip: CGFloat = {shape['chip_radius']}\n"
    f"    public static let chipEnd: CGFloat = {shape['chip_end_radius']}\n"
    "}\n",
)
