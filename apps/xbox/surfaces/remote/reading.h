// Reading the view the core published into the page a surface draws.
//
// ## The finding this file is
//
// The Android television surface has a file that this one does not need to be. `browse/Reading.kt`
// exists because Java source could not call the contract at all: note 210 measured 184
// name-mangled getters across 69 generated classes -- `getTitle-syqQ2Kk()`, `getKind-TNS5Z4k()` --
// and a hyphen is not a legal character in a Java identifier, so one Kotlin file read the contract
// and handed the rest of that package plain strings and integers. (The Android build registered
// the generated `Contract.java` on its Java source set on 2026-11-13, which closes that gate there
// too; the seam is a file they can now delete and this family never had.)
//
// C++ has none of that. `platform/contract/generated/types/Contract.hpp` is 9,107 lines of plain
// aggregates with a `read` and a `write` each and a JSON parser beside them, and `gen/src/cpp.rs`
// emits it today. So this surface reads `contract::Section`, `contract::Tile` and
// `contract::NavItem` directly, and the whole of the Kotlin seam's reason to exist is absent here.
// What is left is this file, which is not a seam but a reading: the three answers that decide what
// a page may draw, and the flattening into `place::Feed`.
//
// Note 220 named the missing `cpp.rs` as Xbox's next blocker and note 223 corrected it to a
// Windows machine. This file is the proof of the first half of that correction: the contract is
// readable from C++ today, on this machine, with no Windows and nothing generated by hand.
//
// ## What it is a twin of
//
//     answerIsThisPage, rowsOn, heroOn   browse/Page.kt          what a page may draw
//     tall, wide                         shared/Art.kt:19-22     which picture goes in which place
//     face                               shared/Face.kt:35       a profile picture made absolute
//     tabs                               browse/TopBar.kt:42     which nav items are tabs
//     cardOf, rowOf, feedOf              browse/Reading.kt       the flattening
//
// ## It constructs no contract value
//
// Note 210's rule for making note 204's protobuf swap mechanical: a surface reads a contract value
// through its fields and never builds one. Nothing here builds one. Everything handed out is a
// `std::string`, an `int`, a `bool` or a `place::Feed`.
#ifndef STREAMS_XBOX_READING_H
#define STREAMS_XBOX_READING_H

#include <optional>
#include <string>
#include <vector>

#include "Contract.hpp"
#include "place.h"
#include "watch.h"

namespace streams::reading {

// Whether the answer in hand belongs to the page the viewer is on. `Page.kt:32`.
//
// Home and the kids home name no screen on the route, so there the answer's own name stands for
// it. Games is never the answer's name, so it never owns one -- which is the defect a reviewer
// caught on 2026-11-11: Games has no rows, the core never asks for it and never clears what it
// holds, so the tab drew whatever the tab before it was showing.
bool answerIsThisPage(const std::string &current, const std::optional<std::string> &asked,
                      const std::string &answerName);

// The rows a page draws: the answer's own rows, and the rows read past the first twelve when the
// answer is this page's. A page with nothing of its own draws nothing, whatever is held.
// `Page.kt:39-49`.
std::vector<contract::Section> rowsOn(const std::string &current,
                                      const std::optional<std::string> &asked,
                                      const std::string &answerName,
                                      const std::vector<contract::Section> &answer,
                                      const std::vector<contract::Section> &extra);

// The title the top of a page opens with, or nothing when the page has no hero of its own.
// `Page.kt:52-56`.
std::optional<contract::Tile> heroOn(const std::string &current,
                                     const std::vector<contract::Section> &answer);

// The picture for a wide place, and for a tall one. `shared/Art.kt:19-22`: backdrop, then still,
// then poster for a wide place; poster first for a tall one, and a wide one's answer behind it.
// Empty when there is no picture at all.
std::string wide(const std::optional<std::vector<contract::Image>> &images);
std::string tall(const std::optional<std::vector<contract::Image>> &images);

// A profile's picture, made absolute against the server. `shared/Face.kt:35`: a path on the server
// or a whole address, and anything else is no picture. Done here, once, so nothing below this file
// holds a rule about what a server address looks like.
std::string face(const contract::Profile &person, const std::string &server);

// Which nav items are tabs of the bar: not the genre item, and no more than six.
// `browse/TopBar.kt:42`.
std::vector<contract::NavItem> tabs(const std::vector<contract::NavItem> &nav);

// One tile, flattened. `Reading.kt:cardOf`.
place::Feed::Card cardOf(const contract::Tile &tile);

// Everything a page of rows draws, flattened. `Reading.kt:feedOf`.
//
// `person` and `lead` are absent rather than null, which is the same shape the Kotlin's nullable
// parameters have. The three answers that decide what a page may draw -- `rowsOn`, `heroOn`,
// `answerIsThisPage` -- are called by the screen and passed in here, so this function has one job,
// exactly as the Kotlin says.
place::Feed feedOf(const std::vector<contract::NavItem> &bar, int active,
                   const std::optional<contract::Profile> &person, const std::string &server,
                   const std::vector<contract::Section> &rows,
                   const std::optional<contract::Tile> &lead, const std::string &empty);

// One `contract::TimeWindow`, flattened into `watch::Window`.
watch::Window windowOf(const contract::TimeWindow &window);

// A list of `contract::TimeWindow` marks (from `contract::Marks` or `contract::PlayView`),
// flattened into `watch::Window`.
std::vector<watch::Window> windowsOf(const std::vector<contract::TimeWindow> &windows);

// `contract::PlayView`, flattened into `watch::Play`.
watch::Play playOf(const contract::PlayView &view);

} // namespace streams::reading

#endif // STREAMS_XBOX_READING_H
