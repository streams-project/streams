    struct Memory;
    impl Grow for Memory {
        fn grow(&self, pages: usize) -> Option<usize> {
            let old = memory_grow(0, pages);
            (old != usize::MAX).then_some(old * PAGE)
        }
    }

    #[global_allocator]
    static HEAP: Heap<Memory> = Heap::new(Memory);

    #[panic_handler]
    fn panic(_: &PanicInfo<'_>) -> ! {
        unreachable()
    }

    unsafe fn input<'a>(at: *const u8, len: usize) -> Option<&'a [u8]> {
        if len == 0 {
            return Some(&[]);
        }
        if at.is_null() {
            return None;
        }
        // SAFETY: the host promises `len` readable bytes at this address.
        Some(unsafe { slice::from_raw_parts(at, len) })
    }

    unsafe fn give(bytes: Vec<u8>, out_ptr: *mut *mut u8, out_len: *mut usize) -> i32 {
        if out_ptr.is_null() || out_len.is_null() {
            return 3;
        }
        let mut boxed = bytes.into_boxed_slice();
        let len = boxed.len();
        let at = boxed.as_mut_ptr();
        core::mem::forget(boxed);
        // SAFETY: both pointers were checked above.
        unsafe {
            ptr::write(out_ptr, at);
            ptr::write(out_len, len);
        }
        0
    }

    macro_rules! trip {
        ($name:ident, $ty:ty) => {
            #[unsafe(no_mangle)]
            pub unsafe extern "C" fn $name(
                at: *const u8,
                len: usize,
                out_ptr: *mut *mut u8,
                out_len: *mut usize,
            ) -> i32 {
                use prost::Message as _;
                // SAFETY: the host's promise about its own pointers.
                let Some(bytes) = (unsafe { input(at, len) }) else {
                    return 3;
                };
                let Ok(value) = <$ty>::decode(bytes) else {
                    return 1;
                };
                // SAFETY: as above.
                unsafe { give(value.encode_to_vec(), out_ptr, out_len) }
            }
        };
    }

