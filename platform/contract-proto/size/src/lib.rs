//! The byte cost of the schema and of the generated validator.
//!
//! Built exactly as the spike's size/wire was - same profile, same target, same
//! allocator, same sixteen types, same round trip - so the numbers can be set beside
//! each other. The difference from size/wire is that these sixteen types come out of
//! the WHOLE contract's generated module rather than a sixteen type subset of it,
//! and that `--features validate` links every generated validator.
